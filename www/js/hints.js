/* =========================================================
   猫カフェからの脱出 - hints.js

   全ヒントを
   「ヒント1 → ヒント2 → 答え」
   の3段階で管理する。

   仕様:
   - 新しい段階を初めて開放するときだけリワード広告を見る。
   - 一度開放したヒントは広告なしで何度でも確認できる。
   - 開放状況は state.hintState.unlocked に保存する。
   - usedHintCount は広告で新しい段階を開放した回数。
   - 現在の進行は、可能な限り「完了フラグ」を優先して判定する。
   - 消費済みアイテムの非所持を理由に、過去のヒントへ戻らない。
   ========================================================= */

const HINT_MAX_LEVEL = 3;


// =========================================================
// hintState 初期化
// =========================================================

function ensureHintState() {
  if (
    !state.hintState ||
    typeof state.hintState !== "object"
  ) {
    state.hintState = {};
  }

  if (
    !state.hintState.unlocked ||
    typeof state.hintState.unlocked !== "object"
  ) {
    state.hintState.unlocked = {};
  }

  // 以前のKEY BOX試験実装からの引き継ぎ
  if (
    typeof state.hintState.keyBoxStage === "number" &&
    !state.hintState.unlocked.keyBox
  ) {
    state.hintState.unlocked.keyBox =
      Math.max(
        0,
        Math.min(
          HINT_MAX_LEVEL,
          state.hintState.keyBoxStage
        )
      );
  }
}


// =========================================================
// ヒントデータ生成
// =========================================================

function makeHintStep(
  id,
  hint1,
  hint2,
  answer
) {
  return {
    id,
    texts: [
      hint1,
      hint2,
      answer,
    ],
  };
}


