// =========================================================
// 開放レベル取得
// =========================================================

function getHintUnlockedLevel(stepId) {
  ensureHintState();

  const raw =
    Number(
      state.hintState.unlocked[stepId] || 0
    );

  const value =
    Number.isFinite(raw)
      ? raw
      : 0;

  return Math.max(
    0,
    Math.min(
      HINT_MAX_LEVEL,
      value
    )
  );
}


// =========================================================
// 開放レベル保存
// =========================================================

function setHintUnlockedLevel(
  stepId,
  level
) {
  ensureHintState();

  state.hintState.unlocked[stepId] =
    Math.max(
      0,
      Math.min(
        HINT_MAX_LEVEL,
        level
      )
    );
}


// =========================================================
// 現在のヒントが1段階以上開放済みか
// =========================================================

function hasUnlockedHintForCurrentStep() {
  const step =
    getCurrentHintStep();

  if (!step) {
    return false;
  }

  return (
    getHintUnlockedLevel(step.id) > 0
  );
}


// =========================================================
// 次の段階を開放
// =========================================================

function unlockNextHintForCurrentStep() {
  const step =
    getCurrentHintStep();

  if (!step) {
    return 0;
  }

  const current =
    getHintUnlockedLevel(step.id);

  const next =
    Math.min(
      HINT_MAX_LEVEL,
      current + 1
    );

  setHintUnlockedLevel(
    step.id,
    next
  );

  return next;
}


// =========================================================
// リワード広告完了時
// =========================================================

function grantHintReward() {

  // HINT画面から
  // 「次のヒントを見る」を押した場合は
  // previousScreenをHINTで上書きしない。
  const alreadyOnHintScreen =
    state.screen === SCREEN.HINT;

  state.usedHintCount =
    (state.usedHintCount || 0) + 1;

  unlockNextHintForCurrentStep();

  saveGame();

  if (alreadyOnHintScreen) {
    renderHintScreen();
    return;
  }

  showScreen(
    SCREEN.HINT,
    {
      rememberPrevious: true,
    }
  );
}


// =========================================================
// 開放済みヒント本文
// =========================================================

function getCurrentUnlockedHintText() {

  const step =
    getCurrentHintStep();

  if (!step) {
    return "";
  }

  const level =
    getHintUnlockedLevel(step.id);

  if (level <= 0) {
    return "まだヒントは開放されていません。";
  }

  const labels = [
    "ヒント1",
    "ヒント2",
    "答え",
  ];

  const blocks = [];

  for (
    let i = 0;
    i < level;
    i += 1
  ) {
    blocks.push(
      `${labels[i]}\n${step.texts[i]}`
    );
  }

  return blocks.join("\n\n");
}


// =========================================================
// 次のヒントを開放できるか
// =========================================================

function canUnlockNextHintForCurrentStep() {

  const step =
    getCurrentHintStep();

  if (!step) {
    return false;
  }

  return (
    getHintUnlockedLevel(step.id) <
    HINT_MAX_LEVEL
  );
}


// =========================================================
// 旧コード互換
// =========================================================

function getCurrentHint() {
  return getCurrentUnlockedHintText();
}